"""
Prepare D-FINE-N / DETR Partitioned COCO JSON Datasets
======================================================
Partitions master COCO annotations (dataset/annotations.json) into:
  - dataset/coco/instances_train.json (8 training subjects)
  - dataset/coco/instances_val.json   (3 validation subjects)
  - dataset/coco/instances_test.json  (3 test subjects)

Features:
- Full COCO format compliance with standard bounding box: [x_min, y_min, width, height]
- Strict subject disjointness matching dataset/splits.json
- Preserves the 4-class ontology:
    1: yawning
    2: hand_over_mouth
    3: drinking
    4: phone_use
- Generates D-FINE dataset YAML configuration
"""

import os
import json
import random
from collections import defaultdict, Counter
from pathlib import Path

def check(cond: bool, msg: str):
    if not cond:
        raise ValueError(msg)

def prepare_dfine_coco():
    repo_root = Path(__file__).resolve().parent.parent
    annotations_file = repo_root / "dataset" / "annotations.json"
    splits_file = repo_root / "dataset" / "splits.json"
    coco_out_dir = repo_root / "dataset" / "coco"

    print(f"Loading master COCO annotations from {annotations_file}...")
    with open(annotations_file, "r", encoding="utf-8") as f:
        master_coco = json.load(f)

    print(f"Loading splits definition from {splits_file}...")
    with open(splits_file, "r", encoding="utf-8") as f:
        splits = json.load(f)

    os.makedirs(coco_out_dir, exist_ok=True)

    # Build subject -> split mapping
    subject_to_split = {}
    for split_name, subjects in splits.items():
        for subj in subjects:
            subject_to_split[subj] = split_name

    # Group annotations by image_id
    img_to_anns = defaultdict(list)
    for ann in master_coco.get("annotations", []):
        img_to_anns[ann["image_id"]].append(ann)

    split_coco = {}
    split_box_counts = {}
    split_filename_map = {
        "train": "instances_train.json",
        "validation": "instances_val.json",
        "test": "instances_test.json"
    }

    for split_name in ["train", "validation", "test"]:
        split_coco[split_name] = {
            "info": {
                "description": f"DMS-Eval {split_name.capitalize()} Split (D-FINE/DETR Format)",
                "url": master_coco.get("info", {}).get("url", ""),
                "version": "1.0",
                "year": 2026,
                "contributor": "DMS-Eval Research Team",
                "date_created": master_coco.get("info", {}).get("date_created", "")
            },
            "licenses": master_coco.get("licenses", []),
            "images": [],
            "annotations": [],
            "categories": master_coco.get("categories", [])
        }
        split_box_counts[split_name] = Counter()

    for img in master_coco["images"]:
        img_id = img["id"]
        rel_file_name = img["file_name"]

        parts = Path(rel_file_name).parts
        if len(parts) >= 2 and parts[0] == "images":
            subject_id = parts[1]
        else:
            subject_id = parts[0]

        split_name = subject_to_split.get(subject_id)
        if not split_name:
            raise ValueError(f"Subject {subject_id} not recognized in splits.json!")

        split_coco[split_name]["images"].append(img)
        anns = img_to_anns.get(img_id, [])
        for ann in anns:
            split_coco[split_name]["annotations"].append(ann)
            split_box_counts[split_name][ann["category_id"]] += 1

    # D-FINE consumes this array through a shuffled sampler, but the derived
    # artifact itself is also frozen to the protocol's seed-13 train order.
    random.Random(13).shuffle(split_coco["train"]["images"])
    train_rank = {image["id"]: rank for rank, image in enumerate(split_coco["train"]["images"])}
    split_coco["train"]["annotations"].sort(key=lambda annotation: (train_rank[annotation["image_id"]], annotation["id"]))

    total_images_written = 0
    total_boxes_written = 0

    print("\n=== Writing Partitioned COCO JSONs ===")
    for split_name, filename in split_filename_map.items():
        out_path = coco_out_dir / filename
        data = split_coco[split_name]
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)

        n_imgs = len(data["images"])
        n_anns = len(data["annotations"])
        total_images_written += n_imgs
        total_boxes_written += n_anns

        cues = split_box_counts[split_name]
        print(f"  [{split_name:10s}] -> {out_path.name:22s} | {n_imgs:5d} images, {n_anns:4d} annotations "
              f"(yawn: {cues[1]}, hand_over_mouth: {cues[2]}, drink: {cues[3]}, phone: {cues[4]})")

    # Generate D-FINE configuration YAML
    dfine_config_path = coco_out_dir / "dfine_dataset.yml"
    dfine_config_content = f"""# DMS-Eval D-FINE-N / RT-DETR Dataset Configuration
# Auto-generated by scripts/prepare_dfine_coco.py

dataset_dir: dataset
image_dir: images

train_ann: dataset/coco/instances_train.json
val_ann: dataset/coco/instances_val.json
test_ann: dataset/coco/instances_test.json

num_classes: 4
remap_mscoco_category: False

# Category ontology (1-indexed COCO ID to name)
category_map:
  1: yawning
  2: hand_over_mouth
  3: drinking
  4: phone_use
"""
    with open(dfine_config_path, "w", encoding="utf-8") as f:
        f.write(dfine_config_content)
    print(f"\nWrote D-FINE dataset configuration to {dfine_config_path}")

    # Global Assertions
    check(total_images_written == len(master_coco["images"]), f"Image count mismatch: {total_images_written} vs {len(master_coco['images'])}")
    check(total_boxes_written == len(master_coco["annotations"]), f"Annotation count mismatch: {total_boxes_written} vs {len(master_coco['annotations'])}")
    print("D-FINE/DETR COCO JSON preparation PASSED: All splits verified with exact parity.")

if __name__ == "__main__":
    prepare_dfine_coco()
